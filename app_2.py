@st.cache_resource
def cargar_modelo():

    with open("modelo_SNIES_completo.pkl", "rb") as archivo_mod:
        artefacto = pickle.load(archivo_mod)

    return artefacto


try:
    artefacto = cargar_modelo()

    modelo = artefacto["modelo"]

    variables = artefacto["configuracion"][
        "variables_predictoras"
    ]

except Exception as e:

    st.error(f"Error al cargar el modelo: {e}")
    st.stop()


# ==========================================================
# 5. INFORMACIÓN DEL MODELO
# ==========================================================

c1, c2, c3 = st.columns(3)

c1.metric("Algoritmo", "Random Forest")
c2.metric("Variables predictoras", len(variables))
c3.metric("Categorías", "3 niveles")

st.divider()


# ==========================================================
# 6. CARGAR ARCHIVO
# ==========================================================

st.markdown(
    '<div class="section-title">1. Cargar información</div>',
    unsafe_allow_html=True
)

st.write(
    "Selecciona un archivo CSV con la información de "
    "los programas académicos que deseas clasificar."
)

archivo = st.file_uploader(
    "Seleccionar archivo CSV",
    type=["csv"]
)

if archivo is None:

    st.info("Carga un archivo CSV para comenzar el análisis.")

    st.markdown("""
    **Requisitos del archivo:**

    - Debe contener todas las variables predictoras.
    - Debe respetar los nombres de las columnas utilizadas durante
      el entrenamiento.
    - No es necesario incorporar la variable objetivo.
    """)

    st.stop()

else:
    # ==========================================================
    # 7. VALIDACIÓN Y LECTURA
    # ==========================================================

    contenido = archivo.getvalue()

    identificador = hashlib.md5(contenido).hexdigest()

    if st.session_state.get("archivo_actual") != identificador:

        st.session_state.pop("resultados_snies", None)

        st.session_state["archivo_actual"] = identificador


    try:

        datos_originales = pd.read_csv(archivo)

    except Exception as e:

        st.error(f"No fue posible leer el CSV: {e}")
        st.stop()


    if datos_originales.empty:

        st.warning("El archivo no contiene registros.")
        st.stop()


    faltantes = [
        col for col in variables
        if col not in datos_originales.columns
    ]

    if faltantes:

        st.error("El archivo no contiene todas las variables requeridas.")

        st.write("Variables faltantes:")

        for col in faltantes:
            st.write(f"- {col}")

        st.stop()


    datos = datos_originales[variables].copy()


    st.success("Archivo cargado y estructura validada correctamente.")


    # ==========================================================
    # 8. RESUMEN DE LOS DATOS
    # ==========================================================

    st.markdown(
        '<div class="section-title">2. Resumen de información</div>',
        unsafe_allow_html=True
    )

    a, b, c = st.columns(3)

    a.metric("Registros", len(datos))

    b.metric("Variables predictoras", len(variables))

    c.metric("Variables faltantes", 0)

    with st.expander("Explorar datos de entrada"):

        st.dataframe(
            datos_originales.head(15),
            use_container_width=True
        )

        st.caption(
            f"Vista previa de los primeros 15 registros "
            f"de {len(datos_originales)}."
        )


    # ==========================================================
    # 9. GENERAR PREDICCIONES
    # ==========================================================

    st.divider()

    st.markdown(
        '<div class="section-title">3. Clasificación</div>',
        unsafe_allow_html=True
    )

    st.write(
        "El modelo Random Forest determinará el nivel de "
        "matriculación futura para cada programa académico."
    )

    if st.button("🚀 Generar predicciones", use_container_width=True):

        try:

            with st.spinner("Ejecutando el modelo Random Forest..."):

                predicciones = modelo.predict(datos)

                resultados = datos_originales.copy()

                resultados["CLASE_PREDICHA"] = predicciones

                # Probabilidades de clasificación, si están disponibles

                if hasattr(modelo, "predict_proba"):

                    probabilidades = modelo.predict_proba(datos)

                    clases = modelo.classes_

                    for i, clase in enumerate(clases):

                        nombre_columna = (
                            "PROBABILIDAD_" + str(clase).upper()
                        )

                        resultados[nombre_columna] = (
                            probabilidades[:, i] * 100
                        ).round(2)

                st.session_state["resultados_snies"] = resultados

            st.success("Clasificación realizada correctamente.")

        except Exception as e:

            st.error(f"Error durante la predicción: {e}")


    # ==========================================================
    # 10. RESULTADOS
    # ==========================================================

    if "resultados_snies" not in st.session_state:

        st.info("Ejecuta la clasificación para visualizar los resultados.")

        st.stop()


    resultados = st.session_state["resultados_snies"].copy()


    # ==========================================================
    # 11. NORMALIZAR CATEGORÍAS
    # ==========================================================

    def identificar_clase(valor):

        valor = str(valor).strip().lower()

        equivalencias = {
            "alto": "Alto",
            "alta": "Alto",
            "medio": "Medio",
            "media": "Medio",
            "bajo": "Bajo",
            "baja": "Bajo"
        }

        return equivalencias.get(valor, str(valor))


    resultados["_NIVEL"] = resultados[
        "CLASE_PREDICHA"
    ].apply(identificar_clase)


    # ==========================================================
    # 12. ANÁLISIS GENERAL
    # ==========================================================

    st.divider()

    st.markdown(
        '<div class="section-title">4. Análisis general</div>',
        unsafe_allow_html=True
    )

    conteo = resultados["_NIVEL"].value_counts()

    total = len(resultados)

    alto = int((resultados["_NIVEL"] == "Alto").sum())

    medio = int((resultados["_NIVEL"] == "Medio").sum())

    bajo = int((resultados["_NIVEL"] == "Bajo").sum())


    # Indicadores

    m1, m2, m3, m4 = st.columns(4)

    m1.metric("Total clasificado", total)

    m2.metric(
        "Nivel ALTO",
        alto,
        f"{alto / total * 100:.1f}%"
    )

    m3.metric(
        "Nivel MEDIO",
        medio,
        f"{medio / total * 100:.1f}%"
    )

    m4.metric(
        "Nivel BAJO",
        bajo,
        f"{bajo / total * 100:.1f}%"
    )


    # Gráficos generales

    col1, col2 = st.columns(2)

    orden = ["Alto", "Medio", "Bajo"]

    distribucion = pd.DataFrame({
        "Nivel": orden,
        "Cantidad": [
            int((resultados["_NIVEL"] == nivel).sum())
            for nivel in orden
        ]
    })

    colores = {
        "Alto": "#16A085",
        "Medio": "#F39C12",
        "Bajo": "#E74C3C"
    }

    with col1:

        st.markdown("#### Distribución de programas")

        fig = px.pie(
            distribucion,
            names="Nivel",
            values="Cantidad",
            color="Nivel",
            color_discrete_map=colores,
            hole=0.55
        )

        fig.update_layout(
            height=350,
            legend_title="Nivel"
        )

        st.plotly_chart(fig, use_container_width=True)


    with col2:

        st.markdown("#### Número de programas por nivel")

        fig = px.bar(
            distribucion,
            x="Nivel",
            y="Cantidad",
            color="Nivel",
            color_discrete_map=colores,
            text="Cantidad"
        )

        fig.update_layout(
            height=350,
            showlegend=False,
            xaxis_title="Nivel de matrícula",
            yaxis_title="Número de programas"
        )

        st.plotly_chart(fig, use_container_width=True)


    # ==========================================================
    # 13. ANÁLISIS COMPARATIVO
    # ==========================================================

    st.divider()

    st.markdown(
        '<div class="section-title">5. Análisis comparativo</div>',
        unsafe_allow_html=True
    )

    st.write(
        "Explora cómo se distribuyen los niveles de matrícula "
        "entre las diferentes instituciones, programas o "
        "ubicaciones disponibles en el archivo."
    )


    # Detectar dimensiones de comparación

    preferidas = [
        "NOMBRE_IES",
        "IES",
        "INSTITUCION",
        "INSTITUCIÓN",
        "NOMBRE_PROGRAMA",
        "PROGRAMA",
        "DEPARTAMENTO",
        "MUNICIPIO",
        "MODALIDAD",
        "NIVEL_ACADEMICO",
        "CARACTER_ACADEMICO",
        "SECTOR"
    ]

    columnas_comparacion = []

    for col in resultados.columns:

        if col.startswith("PROBABILIDAD_") or col in [
            "CLASE_PREDICHA", "_NIVEL"
        ]:
            continue

        nombre = col.upper()

        es_preferida = (
            nombre in preferidas
            or any(
                palabra in nombre
                for palabra in [
                    "INSTITUCION",
                    "INSTITUCIÓN",
                    "PROGRAMA",
                    "DEPARTAMENTO",
                    "MUNICIPIO",
                    "MODALIDAD"
                ]
            )
        )

        es_categorica = (
            pd.api.types.is_object_dtype(resultados[col])
            or isinstance(resultados[col].dtype, pd.CategoricalDtype)
            or pd.api.types.is_bool_dtype(resultados[col])
        )

        if es_preferida or es_categorica:

            if resultados[col].nunique(dropna=True) > 1:
                columnas_comparacion.append(col)


    if not columnas_comparacion:

        st.warning(
            "No se identificaron variables adecuadas para realizar "
            "comparaciones. Revisa las columnas del archivo."
        )

    else:

        # Selección de dimensión

        dimension = st.selectbox(
            "Selecciona la dimensión de análisis",
            columnas_comparacion,
            format_func=lambda x: x.replace("_", " ").title()
        )

        # Filtrar categorías con datos válidos

        comparacion = resultados[
            resultados[dimension].notna()
        ].copy()

        # Número de categorías

        top_n = st.slider(
            "Número de categorías para visualizar",
            min_value=3,
            max_value=20,
            value=min(10, max(3, comparacion[dimension].nunique()))
        )

        # Seleccionar las categorías con más registros

        principales = (
            comparacion[dimension]
            .value_counts()
            .head(top_n)
            .index
        )

        comparacion = comparacion[
            comparacion[dimension].isin(principales)
        ]

        # Agrupación

        agrupado = (
            comparacion.groupby(
                [dimension, "_NIVEL"],
                observed=False
            )
            .size()
            .reset_index(name="Cantidad")
        )

        col3, col4 = st.columns(2)

        with col3:

            st.markdown("#### Distribución comparativa")

            fig = px.bar(
                agrupado,
                x=dimension,
                y="Cantidad",
                color="_NIVEL",
                barmode="group",
                color_discrete_map=colores,
                category_orders={
                    "_NIVEL": orden
                }
            )

            fig.update_layout(
                height=450,
                xaxis_title=dimension.replace("_", " ").title(),
                yaxis_title="Número de programas",
                legend_title="Nivel",
                xaxis_tickangle=-35
            )

            st.plotly_chart(fig, use_container_width=True)


        with col4:

            st.markdown("#### Participación porcentual")

            agrupado_pct = agrupado.copy()

            agrupado_pct["Porcentaje"] = (
                agrupado_pct["Cantidad"]
                / agrupado_pct.groupby(dimension)["Cantidad"]
                .transform("sum")
                * 100
            )

            fig = px.bar(
                agrupado_pct,
                x=dimension,
                y="Porcentaje",
                color="_NIVEL",
                barmode="stack",
                color_discrete_map=colores,
                category_orders={
                    "_NIVEL": orden
                }
            )

            fig.update_layout(
                height=450,
                xaxis_title=dimension.replace("_", " ").title(),
                yaxis_title="Participación (%)",
                legend_title="Nivel",
                xaxis_tickangle=-35,
                yaxis_range=[0, 100]
            )

            st.plotly_chart(fig, use_container_width=True)


        with st.expander("Consultar tabla comparativa"):

            tabla = agrupado.pivot(
                index=dimension,
                columns="_NIVEL",
                values="Cantidad"
            ).fillna(0)

            tabla = tabla.reindex(
                columns=orden,
                fill_value=0
            )

            st.dataframe(
                tabla,
                use_container_width=True
            )


    # ==========================================================
    # 14. FILTROS Y EXPLORACIÓN DE RESULTADOS
    # ==========================================================

    st.divider()

    st.markdown(
        '<div class="section-title">6. Explorar resultados</div>',
        unsafe_allow_html=True
    )

    # Filtro por clase

    clases_disponibles = [
        clase for clase in orden
        if clase in resultados["_NIVEL"].unique()
    ]

    clases_seleccionadas = st.multiselect(
        "Filtrar por nivel de matrícula",
        options=clases_disponibles,
        default=clases_disponibles
    )

    filtrados = resultados[
        resultados["_NIVEL"].isin(clases_seleccionadas)
    ].copy()


    # Filtro adicional por dimensión

    if columnas_comparacion:

        filtro_dimension = st.selectbox(
            "Filtrar por variable",
            ["Sin filtro"] + columnas_comparacion
        )

        if filtro_dimension != "Sin filtro":

            valores = sorted(
                filtrados[filtro_dimension]
                .dropna()
                .unique()
                .tolist(),
                key=str
            )

            seleccion = st.multiselect(
                f"Seleccionar {filtro_dimension}",
                valores,
                default=valores
            )

            filtrados = filtrados[
                filtrados[filtro_dimension].isin(seleccion)
            ]


    st.metric("Registros después de aplicar filtros", len(filtrados))


    st.dataframe(
        filtrados.drop(columns=["_NIVEL"]),
        use_container_width=True,
        height=450
    )


    # ==========================================================
    # 15. DESCARGAR RESULTADOS
    # ==========================================================

    st.divider()

    st.markdown(
        '<div class="section-title">7. Descargar resultados</div>',
        unsafe_allow_html=True
    )

    col5, col6 = st.columns(2)

    with col5:

        csv_completo = resultados.drop(
            columns=["_NIVEL"]
        ).to_csv(
            index=False,
            encoding="utf-8-sig"
        )

        st.download_button(
            "⬇️ Descargar clasificación completa",
            data=csv_completo,
            file_name="predicciones_SNIES_completas.csv",
            mime="text/csv",
            use_container_width=True
        )

    with col6:

        csv_filtrado = filtrados.drop(
            columns=["_NIVEL"]
        ).to_csv(
            index=False,
            encoding="utf-8-sig"
        )

        st.download_button(
            "⬇️ Descargar resultados filtrados",
            data=csv_filtrado,
            file_name="predicciones_SNIES_filtradas.csv",
            mime="text/csv",
            use_container_width=True
        )


# ==========================================================
