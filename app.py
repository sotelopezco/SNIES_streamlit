import streamlit as st

# Configuración de la página
st.set_page_config(
    page_title="Predicción SNIES",
    page_icon="📊",
    layout="centered"
)

st.title("Predicción de matrícula - SNIES")
st.write(
    "Aplicación para clasificar la tasa de matriculación "
    "futura de los programas académicos."
)

# Cargar modelo
@st.cache_resource
def cargar_modelo():
    import pickle
    with open("modelo_SNIES_completo.pkl", "rb") as archivo:
        artefacto = pickle.load(archivo)
    return artefacto

artefacto = cargar_modelo()
modelo = artefacto["modelo"]

# Variables requeridas por el modelo
variables = artefacto["configuracion"]["variables_predictoras"]

st.subheader("Cargar información")

archivo = st.file_uploader(
    "Selecciona un archivo CSV",
    type=["csv"]
)

if archivo is not None:

    datos = pd.read_csv(archivo)

    # Verificar columnas
    faltantes = [col for col in variables if col not in datos.columns]

    if faltantes:
        st.error(
            "Faltan las siguientes variables: "
            + ", ".join(faltantes)
        )

    else:
        datos = datos[variables]

        st.write("Registros cargados:", len(datos))

        if st.button("Generar predicciones"):

            predicciones = modelo.predict(datos)

            resultados = datos.copy()
            resultados["CLASE_PREDICHA"] = predicciones

            st.success("Predicciones generadas correctamente")

            st.subheader("Resultados")
            st.dataframe(resultados, use_container_width=True)

            # Descargar resultados
            csv = resultados.to_csv(
                index=False,
                encoding="utf-8-sig"
            )

            st.download_button(
                label="Descargar resultados",
                data=csv,
                file_name="predicciones_SNIES.csv",
                mime="text/csv"
            )

